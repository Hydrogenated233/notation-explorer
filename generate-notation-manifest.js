'use strict'

const fs = require('node:fs')
const path = require('node:path')
const NotationFileIndex = require('./js/notation-file-index.js')

const projectRoot = __dirname
const notationRoot = path.join(projectRoot, 'js', 'notations')
const manifestPath = path.join(projectRoot, 'js', 'notation-manifest.js')

function discoverNotationFiles(root = notationRoot) {
   const discovered = []

   function walk(directory, categories) {
      const entries = fs.readdirSync(directory, { withFileTypes: true })
      for (const entry of entries) {
         const absolute = path.join(directory, entry.name)
         if (entry.isDirectory()) {
            const nextCategories = categories.concat(entry.name)
            if (nextCategories.length > NotationFileIndex.MAX_CATEGORY_DEPTH) {
               throw new Error(
                  `Notation categories may be at most ${NotationFileIndex.MAX_CATEGORY_DEPTH} levels deep: ` +
                  nextCategories.join('/')
               )
            }
            walk(absolute, nextCategories)
         } else if (entry.isFile()) {
            const relative = categories.concat(entry.name).join('/')
            if (NotationFileIndex.isEnabledPath(relative)) discovered.push(relative)
         }
      }
   }

   walk(root, [])
   return NotationFileIndex.sortPaths(discovered)
}

function renderManifest(files) {
   const body = JSON.stringify(files, null, 3)
   return `// Generated by node generate-notation-manifest.js. Do not edit by hand.\n` +
      `;(function (root, factory) {\n` +
      `   var files = factory()\n` +
      `   if (typeof module === 'object' && module.exports) module.exports = files\n` +
      `   else root.BUILTIN_NOTATION_FILES = files\n` +
      `})(typeof globalThis !== 'undefined' ? globalThis : this, function () {\n` +
      `   return Object.freeze(${body})\n` +
      `})\n`
}

function currentManifestSource() {
   return renderManifest(discoverNotationFiles())
}

function writeManifest() {
   const source = currentManifestSource()
   fs.writeFileSync(manifestPath, source, 'utf8')
   return source
}

function normalizeLineEndings(source) {
   return source.replace(/\r\n/g, '\n')
}

function checkManifest() {
   const expected = currentManifestSource()
   const actual = fs.existsSync(manifestPath) ? fs.readFileSync(manifestPath, 'utf8') : ''
   return normalizeLineEndings(actual) === normalizeLineEndings(expected)
}

if (require.main === module) {
   if (process.argv.includes('--check')) {
      if (!checkManifest()) {
         console.error('js/notation-manifest.js is stale. Run: node generate-notation-manifest.js')
         process.exitCode = 1
      }
   } else {
      const files = discoverNotationFiles()
      writeManifest()
      console.log(`Generated js/notation-manifest.js with ${files.length} notation files.`)
   }
}

module.exports = {
   notationRoot,
   manifestPath,
   discoverNotationFiles,
   renderManifest,
   currentManifestSource,
   writeManifest,
   normalizeLineEndings,
   checkManifest,
}
